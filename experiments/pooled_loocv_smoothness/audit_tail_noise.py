"""Reproduce the executed d=1,2,3 and 13-distribution tail-noise pilot audit.

This reads ONLY saved method_comparison.csv and its manifest: never
reruns the DGP, never selects lambda using tau, and never calls GitHub.
Every estimator is paired within (scenario_id, replicate, R).
R=1/R=3 intentionally reuse the first observed series; these are NOT
independent simulations. Report results by d and distribution.

Cauchy observation noise has no population variance and therefore
no finite expected squared reconstruction risk; finite realized MSE
is only a per-realization diagnostic. Use robust absolute errors.
Optional figures are manual-only, not generated by CI.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

from .run_tail_noise import DIFFERENCE_ORDERS, METHODS, REGIMES, SKEW_NORMAL_ALPHAS

ML, CV, MULTI = METHODS


def read_pools(csv_path: Path, manifest_path: Path) -> tuple[list[dict], dict]:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    with csv_path.open(newline="", encoding="utf-8") as source:
        data = list(csv.DictReader(source))
    if not data:
        raise ValueError("missing method-level simulation results")
    if len(data) != manifest["expected_method_rows"]:
        raise ValueError("method-level row count does not match manifest")
    if manifest["status"] != "executed":
        raise ValueError("source manifest is not an executed run")
    by_pool: dict[tuple[int, int, int], dict[str, dict]] = defaultdict(dict)
    for row in data:
        key = (int(row["scenario_id"]), int(row["replicate"]), int(row["R"]))
        method = row["method"]
        if method not in METHODS or method in by_pool[key]:
            raise ValueError(f"invalid or repeated method: {key} / {method}")
        by_pool[key][method] = row
    if len(by_pool) != manifest["expected_pools"]:
        raise ValueError("unexpected paired pool count")
    if any(set(methods) != set(METHODS) for methods in by_pool.values()):
        raise ValueError("all three methods must exist in every pool")
    rows = []
    for (sid, rep, r), group in sorted(by_pool.items()):
        item = group[ML]
        for key in ("seed", "regime", "N", "d", "R", "noise_scale"):
            if len({method[key] for method in group.values()}) != 1:
                raise ValueError(f"methods use mismatched {key} within same pool")
        if item["regime"] not in REGIMES:
            raise ValueError("unrecognized regime")
        d = int(item["d"])
        if d not in DIFFERENCE_ORDERS:
            raise ValueError("unrecognized difference order")
        if manifest["scenario_grid"][sid]["d"] != d:
            raise ValueError("difference order inconsistent with manifest")
        if manifest["scenario_grid"][sid]["regime"] != item["regime"]:
            raise ValueError("regime inconsistent with manifest")
        score = lambda method, k: float(group[method][k])
        rows.append({
            "scenario_id": sid, "replicate": rep, "R": r,
            "seed": int(item["seed"]), "regime": item["regime"],
            "d": d, "N": int(item["N"]),
            "noise_scale": float(item["noise_scale"]),
            "skew_normal_alpha": (
                SKEW_NORMAL_ALPHAS.get(item["regime"], float("nan"))),
            "observation_variance_exists": item[
                "observation_variance_exists"].lower() == "true",
            "mse_ml": score(ML, "realized_true_trend_MSE"),
            "mse_cv": score(CV, "realized_true_trend_MSE"),
            "mse_multi": score(MULTI, "realized_true_trend_MSE"),
            "loocv_ml": score(ML, "observed_LOOCV_MSE"),
            "loocv_cv": score(CV, "observed_LOOCV_MSE"),
            "loocv_multi": score(MULTI, "observed_LOOCV_MSE"),
            "median_abs_error_ml": score(
                ML, "realized_median_absolute_trend_error"),
            "median_abs_error_cv": score(
                CV, "realized_median_absolute_trend_error"),
            "p90_abs_error_ml": score(
                ML, "realized_p90_absolute_trend_error"),
            "p90_abs_error_cv": score(
                CV, "realized_p90_absolute_trend_error"),
            "lambda_ml": score(ML, "selected_lambda"),
            "lambda_cv": score(CV, "selected_lambda"),
            "lambda_multi": score(MULTI, "selected_lambda"),
            "stationary_candidates": int(
                score(MULTI, "number_stationary_sign_change_candidates")),
            "paired_mse_cv_minus_ml": score(
                CV, "realized_true_trend_MSE") -
                score(ML, "realized_true_trend_MSE"),
            "paired_loocv_cv_minus_multi": score(
                CV, "observed_LOOCV_MSE") -
                score(MULTI, "observed_LOOCV_MSE"),
        })
    # By manifest construction R1 reuses first member of R3; verify seed and
    # design fields. Data-only evidence cannot prove series equality because
    # raw simulated arrays are not saved: that is checked by generator tests.
    by_replicate: dict[tuple[int, int], dict[int, dict]] = defaultdict(dict)
    for p in rows:
        by_replicate[(p["scenario_id"], p["replicate"])][p["R"]] = p
    for key, grp in by_replicate.items():
        if set(grp) != {1, 3}:
            raise ValueError(f"expected nested R1/R3 pair: {key}")
        if grp[1]["seed"] != grp[3]["seed"]:
            raise ValueError(f"nested seed mismatch: {key}")
    return rows, manifest


def summarize(pools: list[dict]) -> dict:
    def median(xs):
        return float(np.median(xs))

    def mean(xs):
        return float(np.mean(xs))

    def describe(records: list[dict], cauchy: bool) -> dict:
        if not records:
            raise ValueError("cannot describe empty simulation cell")
        obj = {
            "n_primary_R3_pools": len(records),
            "gaussian_ML_lower_realized_MSE_count": sum(
                x["paired_mse_cv_minus_ml"] > 0 for x in records),
            "median_pool_realized_MSE_ML": median([r["mse_ml"] for r in records]),
            "median_pool_realized_MSE_LOOCV": median([r["mse_cv"] for r in records]),
            "median_pool_median_absolute_error_ML": median([
                r["median_abs_error_ml"] for r in records]),
            "median_pool_median_absolute_error_LOOCV": median([
                r["median_abs_error_cv"] for r in records]),
            "median_pool_p90_absolute_error_ML": median([
                r["p90_abs_error_ml"] for r in records]),
            "median_pool_p90_absolute_error_LOOCV": median([
                r["p90_abs_error_cv"] for r in records]),
            "ML_infinite_lambda_count": int(sum(
                bool(np.isinf(r["lambda_ml"])) for r in records)),
            "LOOCV_infinite_lambda_count": int(sum(
                bool(np.isinf(r["lambda_cv"])) for r in records)),
            "bounded_Brent_LOOCV_loss_worse_than_multibracket_gt_1e7":
                sum(r["paired_loocv_cv_minus_multi"] > 1e-7
                    for r in records),
            "stationary_candidate_histogram": dict(
                sorted(Counter(r["stationary_candidates"]
                               for r in records).items())),
        }
        if cauchy:
            obj["population_expected_trend_MSE_defined"] = False
            obj["mean_MSE_omitted_due_to_infinite_Cauchy_risk"] = True
        else:
            obj["population_expected_trend_MSE_defined"] = True
            obj["mean_realized_trend_MSE_ML"] = mean([
                r["mse_ml"] for r in records])
            obj["mean_realized_trend_MSE_LOOCV"] = mean([
                r["mse_cv"] for r in records])
            obj["mean_paired_MSE_LOOCV_minus_ML"] = mean([
                r["paired_mse_cv_minus_ml"] for r in records])
            obj["mean_LOOCV_loss_ML"] = mean([
                r["loocv_ml"] for r in records])
            obj["mean_LOOCV_loss_LOOCV"] = mean([
                r["loocv_cv"] for r in records])
        return obj

    primary = [p for p in pools if p["R"] == 3]
    by_d = {
        str(d): describe([x for x in primary if x["d"] == d and
                          x["observation_variance_exists"]], cauchy=False)
        for d in DIFFERENCE_ORDERS
    }
    by_d_regime = []
    for d in DIFFERENCE_ORDERS:
        for regime in REGIMES:
            cells = [x for x in primary
                     if x["d"] == d and x["regime"] == regime]
            by_d_regime.append({
                "d": d, "regime": regime,
                **describe(cells, cauchy=(regime == "cauchy_observation"))
            })
    by_skew_alpha = [{
        "alpha": alpha,
        **describe([x for x in primary if x["regime"] == regime],
                   cauchy=False),
    } for regime, alpha in SKEW_NORMAL_ALPHAS.items()]
    by_scenario = []
    for sid in sorted({p["scenario_id"] for p in primary}):
        ps = [p for p in primary if p["scenario_id"] == sid]
        ref = ps[0]
        by_scenario.append({
            "scenario_id": sid, "regime": ref["regime"], "d": ref["d"],
            "N": ref["N"], "noise_scale": ref["noise_scale"],
            **describe(ps, cauchy=not ref["observation_variance_exists"])
        })
    finite = [x for x in primary if x["observation_variance_exists"]]
    cauchy = [x for x in primary if not x["observation_variance_exists"]]
    roots_gt_one = [x for x in primary if x["stationary_candidates"] > 1]
    return {
        "status": "independent_csv_audit_of_exploratory_pilot",
        "primary_R3_pools": len(primary),
        "nested_R1_pools": len(pools) - len(primary),
        "method_rows_checked": len(pools) * len(METHODS),
        "finite_variance_primary_R3": describe(finite, cauchy=False),
        "Cauchy_primary_R3": describe(cauchy, cauchy=True),
        "by_d_finite_variance_R3": by_d,
        "by_d_and_regime_R3": by_d_regime,
        "by_skew_normal_alpha_R3": by_skew_alpha,
        "by_scenario_R3": by_scenario,
        "multiple_stationary_candidate_R3_cases": [
            {
                k: p[k] for k in ("scenario_id", "replicate", "seed",
                                "d", "regime", "N", "noise_scale",
                                "stationary_candidates",
                                "paired_loocv_cv_minus_multi")
            } for p in roots_gt_one
        ],
        "warnings": [
            "Only five independent replicates per (d, distribution, N, scale) cell.",
            "R1 is nested in R3; never treat 1560 pools as independent samples.",
            "Latent trend generator is order-matched for each d. Cross-d absolute MSE is not comparable.",
            "The Cauchy distribution has no population variance, Guerrero ratio, or expected squared-error risk.",
            "Stationary sign-change candidates do not prove existence or number of local minima.",
            "Gaussian difference-contrast MLE is an extension; not Guerrero's published estimator.",
            "This is retrospective synthetic latent trend recovery, not stock forecasting.",
        ]
    }


def write_csv(path: Path, records: list[dict]) -> None:
    # Histograms are nested objects and require a simple printable conversion.
    # Some regimes (Cauchy) deliberately omit population-MSE means and
    # include an infinite-risk warning, so preserve the union of columns.
    columns = list(dict.fromkeys(k for record in records for k in record))
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        for rec in records:
            writer.writerow({
                k: json.dumps(v) if isinstance(v, dict) else v
                for k, v in rec.items()
            })


def optional_plots(report: dict, out: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    for d in DIFFERENCE_ORDERS:
        cases = [c for c in report["by_d_and_regime_R3"]
                 if c["d"] == d and c["population_expected_trend_MSE_defined"]]
        x = np.arange(len(cases))
        width = .38
        fig, ax = plt.subplots(figsize=(12, 5))
        ax.bar(x - width/2, [r["mean_realized_trend_MSE_ML"] for r in cases],
               width, label="Gaussian difference likelihood")
        ax.bar(x + width/2, [r["mean_realized_trend_MSE_LOOCV"] for r in cases],
               width, label="Pooled LOOCV bounded Brent")
        ax.set_xticks(x, [r["regime"].replace("_", " ") for r in cases],
                      rotation=45, ha="right")
        ax.set_ylabel("Mean latent trend MSE")
        ax.set_title(f"Matched difference order d={d}; R=3")
        ax.legend()
        fig.tight_layout()
        fig.savefig(out / f"tail_noise_R3_d{d}_finite_variance.png", dpi=160)
        plt.close(fig)


def execute(csv_path: Path, manifest_path: Path, out: Path,
            figures: bool = False) -> dict:
    pools, _ = read_pools(csv_path, manifest_path)
    report = summarize(pools)
    out.mkdir(parents=True, exist_ok=True)
    (out / "audit_summary.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    write_csv(out / "R3_by_d_distribution.csv",
              report["by_d_and_regime_R3"])
    write_csv(out / "R3_by_scenario.csv",
              report["by_scenario_R3"])
    write_csv(out / "paired_pool_diagnostics.csv", pools)
    if figures:
        optional_plots(report, out)
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    base = Path("results/pooled_loocv_smoothness/guerrero/tail_stress/pilot")
    parser.add_argument("--csv", type=Path, default=base / "method_comparison.csv")
    parser.add_argument("--manifest", type=Path, default=base / "manifest.json")
    parser.add_argument("--out-dir", type=Path, default=base / "audit")
    parser.add_argument("--figures", action="store_true")
    args = parser.parse_args()
    report = execute(args.csv, args.manifest, args.out_dir, args.figures)
    print(json.dumps({
        "primary_R3_pools": report["primary_R3_pools"],
        "finite_variance_R3": report["finite_variance_primary_R3"],
        "Cauchy_R3": report["Cauchy_primary_R3"],
    }, indent=2))


if __name__ == "__main__":
    main()
